import { createHash, randomUUID } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const frontendRoot = path.resolve(path.dirname(scriptPath), '..');
const defaultSourceRuntime = path.resolve(
  frontendRoot,
  '..',
  'dist-tauri',
  'backend-runtime',
);
export const defaultTargetRuntime = path.join(
  frontendRoot,
  'src-tauri',
  'backend-runtime',
);
export const expectedBackendVersion = JSON.parse(
  fs.readFileSync(path.join(frontendRoot, 'package.json'), 'utf8'),
).version;
export const expectedUvLockSha256 = createHash('sha256')
  .update(fs.readFileSync(path.resolve(frontendRoot, '..', 'backend', 'uv.lock')))
  .digest('hex');

const layoutKeys = [
  'python_executable',
  'python_home',
  'site_packages',
];

/**
 * Resolve and validate the runtime paths the Rust launcher will consume.
 *
 * Used by staging, the Tauri pre-build gate, and Node contract tests. Every
 * path must be relative to the supplied runtime root and already exist, so
 * moving the root cannot preserve an accidental build-machine dependency.
 */
export function resolveRuntimeLayout(runtimeRoot) {
  const manifestPath = path.join(runtimeRoot, 'runtime-manifest.json');
  let manifest;
  try {
    manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  } catch (error) {
    throw new Error(`Cannot read runtime manifest at ${manifestPath}: ${error.message}`);
  }

  if (manifest.schema_version !== 3) {
    throw new Error(`Unsupported runtime manifest schema: ${manifest.schema_version}`);
  }
  const expectedOs = { darwin: 'macos', win32: 'windows', linux: 'linux' }[process.platform];
  const expectedArch = { arm64: 'aarch64', x64: 'x86_64' }[process.arch];
  if (manifest.target_os !== expectedOs || manifest.target_arch !== expectedArch) {
    throw new Error(
      `Runtime target ${manifest.target_os}/${manifest.target_arch} does not match ${expectedOs}/${expectedArch}`,
    );
  }
  if (
    manifest.backend_version !== expectedBackendVersion
    || manifest.uv_lock_sha256 !== expectedUvLockSha256
    || manifest.python_selector !== '3.14'
    || typeof manifest.python_version !== 'string'
    || !manifest.python_version.startsWith('3.14.')
    || manifest.python_free_threaded !== false
  ) {
    throw new Error('Runtime manifest version, Python, or lock provenance is invalid');
  }

  const resolved = {};
  for (const key of layoutKeys) {
    const relativePath = manifest[key];
    if (
      typeof relativePath !== 'string'
      || relativePath.length === 0
      || path.posix.isAbsolute(relativePath)
      || path.win32.isAbsolute(relativePath)
      || relativePath.split('/').includes('..')
      || relativePath.includes('\\')
    ) {
      throw new Error(`Runtime manifest ${key} must be a portable relative path`);
    }
    const absolutePath = path.join(runtimeRoot, ...relativePath.split('/'));
    if (!fs.existsSync(absolutePath)) {
      throw new Error(`Runtime manifest ${key} does not exist: ${absolutePath}`);
    }
    resolved[key] = absolutePath;
  }

  return { manifest, ...resolved };
}

/**
 * Stage the packaged runtime as the sole Tauri runtime input.
 *
 * Called by the shared runtime-preparation command. Platform-only additions
 * happen after the copy; the relative manifest remains byte-for-byte owned by
 * the Python packager and is validated again before staging succeeds.
 */
export function stageBackendRuntime({
  sourceRuntime = defaultSourceRuntime,
  targetRuntime = defaultTargetRuntime,
  platform = process.platform,
  systemRoot = process.env.SYSTEMROOT || 'C:\\Windows',
} = {}) {
  resolveRuntimeLayout(sourceRuntime);
  fs.mkdirSync(path.dirname(targetRuntime), { recursive: true });
  const stagingRuntime = `${targetRuntime}.staging-${randomUUID()}`;

  try {
    fs.cpSync(sourceRuntime, stagingRuntime, { recursive: true });

    const layout = resolveRuntimeLayout(stagingRuntime);
    if (platform === 'win32') {
      for (const dll of ['msvcp140.dll', 'msvcp140_1.dll', 'concrt140.dll']) {
        const destination = path.join(layout.python_home, dll);
        const source = path.join(systemRoot, 'System32', dll);
        if (!fs.existsSync(destination) && fs.existsSync(source)) {
          fs.copyFileSync(source, destination);
        }
      }

      const sitecustomize = `\
# Auto-generated by stage-backend-runtime.mjs.
# Python 3.8+ requires explicit DLL search registration for bundled extensions.
import os as _os, sys as _sys
if _sys.platform == "win32" and hasattr(_os, "add_dll_directory"):
    _home = _os.environ.get("PYTHONHOME", "")
    if _home and _os.path.isdir(_home):
        _dll_directory = _os.add_dll_directory(_home)
`;
      fs.writeFileSync(
        path.join(layout.site_packages, 'sitecustomize.py'),
        sitecustomize,
        'utf8',
      );
    }

    resolveRuntimeLayout(stagingRuntime);
    fs.rmSync(targetRuntime, { recursive: true, force: true });
    fs.renameSync(stagingRuntime, targetRuntime);
  } finally {
    fs.rmSync(stagingRuntime, { recursive: true, force: true });
  }

  resolveRuntimeLayout(targetRuntime);
  return targetRuntime;
}

const isDirectRun = process.argv[1]
  && path.resolve(process.argv[1]) === scriptPath;

if (isDirectRun) {
  try {
    if (process.argv.includes('--validate-only')) {
      resolveRuntimeLayout(defaultTargetRuntime);
      console.log(`Validated staged backend runtime: ${defaultTargetRuntime}`);
    } else {
      const staged = stageBackendRuntime();
      console.log(`Staged backend runtime to: ${staged}`);
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
