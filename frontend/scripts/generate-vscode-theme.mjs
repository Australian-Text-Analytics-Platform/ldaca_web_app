import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const frontendRoot = fileURLToPath(new URL('..', import.meta.url));
const manifestPath = `${frontendRoot}/theme/vscode-2026.json`;
const outputPath = `${frontendRoot}/src/styles/vscode-2026.generated.css`;
const check = process.argv.includes('--check');

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
const cssName = (name) => `--vscode-${name.replaceAll('.', '-')}`;
const declarationBlock = (tokens) =>
  Object.entries(tokens)
    .map(([name, value]) => `  ${cssName(name)}: ${value};`)
    .join('\n');

const metricBlock = declarationBlock(manifest.metrics);
const themeBlocks = Object.entries(manifest.themes)
  .map(([theme, tokens]) => {
    const selector = theme === 'light-2026' ? `:root,\n[data-theme="${theme}"]` : `[data-theme="${theme}"]`;
    return `${selector} {\n${declarationBlock(tokens)}\n  color-scheme: ${theme === 'dark-2026' ? 'dark' : 'light'};\n}`;
  })
  .join('\n\n');

const generated = `/* Generated by scripts/generate-vscode-theme.mjs. Do not edit directly.\n * Source: VS Code ${manifest.source.version} @ ${manifest.source.commit} (MIT).\n */\n\n:root {\n${metricBlock}\n  --vscode-shadow-lg: 0 4px 16px 0 var(--vscode-widget-shadow);\n}\n\n${themeBlocks}\n`;

if (check) {
  const existing = await readFile(outputPath, 'utf8').catch(() => '');
  if (existing !== generated) {
    console.error('VS Code theme CSS is stale. Run pnpm theme:generate.');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, generated);
}
